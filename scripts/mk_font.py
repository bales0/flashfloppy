import re, sys

# Range of char codes we are interested in
first = 0x20
last = 0x7e

def main(argv):
    in_f = open(argv[1], "r")
    out_f = open(argv[2] + ".c", "w")
    out_f.write("/* Autogenerated by " + argv[0] + " */\n")
    prev = first - 1
    # Find font size
    for line in in_f:
        match = re.match("^FONTBOUNDINGBOX ([0-9]+) ([0-9]+) ([0-9]+) ([-0-9]+)", line)
        if match:
            break
    width = int(match.group(1))
    height = int(match.group(2))
    y_base = int(match.group(4))
    gap = 16 - height
    tgap = gap // 2
    bgap = gap - tgap
    out_f.write("const uint8_t %s[] aligned(4) = {\n" % argv[2])
    for line in in_f:
        # Look for a new character encoding
        match = re.match("^ENCODING ([0-9]+)", line)
        #match = re.match("[ \t]*([A-Za-z0-9-]+)[ \t]*=[ \t]*"
        #                 "([A-Za-z0-9-]+|\".*\")", line)
        if not match:
            continue
        # Extract the decimal character code point
        code = int(match.group(1))
        # Skip uninteresting code points
        if code < first or code > last:
            continue
        # This script assumes the char set is in code-point order
        assert code == prev + 1
        prev = code
        # Scan for start of bitmap data
        x_shift = 0
        top_space = 0
        bottom_space = 0
        for line in in_f:
            bbx = re.match("^BBX ([0-9]+) ([0-9]+) ([0-9]+) ([-0-9]+)", line)
            if bbx:
                x_shift = int(bbx.group(3))
                y_height = int(bbx.group(2))
                y_shift = int(bbx.group(4))
                bottom_space = y_shift - y_base
                top_space = height - (bottom_space + y_height)
            if re.match("BITMAP", line):
                break
        # Process bitmap data up to end-char
        char = []
        top_space += tgap
        for i in range(top_space):
            char.append(0)
        for line in in_f:
            if re.match("ENDCHAR", line):
                break
            match = re.match("([0-9A-F]+)", line)
            char.append(int(match.group(1), 16) >> x_shift)
        bottom_space += bgap
        for i in range(bottom_space):
            char.append(0)
        # Convert row-wise data to column-wise
        while char:
            out_f.write("    ")
            mask = 0x80
            for i in range(width):
                col = 0
                for j in range(8):
                    col //= 2
                    if char[j] & mask:
                        col = col + 0x80
                out_f.write("0x%02x, " % (col))
                mask //= 2
            char = char[8:]
            if not char:
                out_f.write(" /* '%c' %02u */" % (code, code-first))
            out_f.write("\n")
    out_f.write("};\n");
    # Assert we found all interesting code points
    assert prev == last

def font_columns(path):
    """Read the original BDF into 16-bit columns, one indexable glyph at a time."""
    text = open(path).read()
    box = re.search(r'^FONTBOUNDINGBOX (\d+) (\d+) (-?\d+) (-?\d+)', text, re.M)
    width, height, _, base = map(int, box.groups())
    columns = []
    expected = first
    for record in text.split('STARTCHAR ')[1:]:
        encoding = re.search(r'^ENCODING (-?\d+)', record, re.M)
        if encoding is None:
            continue
        code = int(encoding.group(1))
        if code < first or code > last:
            continue
        assert code == expected
        expected += 1
        bbx = re.search(r'^BBX (\d+) (\d+) (-?\d+) (-?\d+)', record, re.M)
        _, rows, xshift, yshift = map(int, bbx.groups())
        top = (16-height)//2 + height - (yshift-base+rows)
        assert 0 <= top and top+rows <= 16
        bitmap = record.split('BITMAP\n', 1)[1].split('ENDCHAR', 1)[0]
        bits = [int(line, 16) for line in bitmap.split()]
        assert len(bits) == rows
        for x in range(width):
            columns.append(sum(((value >> (7-x+xshift)) & 1) << (top+y)
                               for y, value in enumerate(bits)))
    assert expected == last+1
    return columns

def packed(argv):
    """Two original fonts share a lossless byte-indexed column dictionary."""
    small, large = font_columns(argv[2]), font_columns(argv[3])
    out = open(argv[4]+'.c', 'w')
    out.write('/* Autogenerated lossless OLED column dictionaries. */\n')

    def emit(extra):
        palette = sorted(set(small+large if extra else small))
        assert len(palette) <= 256, 'OLED dictionary no longer fits byte indices'
        indices = {column: i for i, column in enumerate(palette)}
        out.write('const uint16_t oled_font_columns[] aligned(4) = {\n')
        for pos in range(0, len(palette), 8):
            out.write('    '+', '.join('0x%04x' % v for v in palette[pos:pos+8])+',\n')
        out.write('};\n')
        for name, values in [('6x13', small)]+([('8x16', large)] if extra else []):
            out.write('const uint8_t oled_font_%s[] aligned(4) = {\n' % name)
            for pos in range(0, len(values), 16):
                out.write('    '+', '.join(str(indices[v]) for v in values[pos:pos+16])+',\n')
            out.write('};\n')

    out.write('#ifdef font_extra\n')
    emit(True)
    out.write('#else\n')
    emit(False)
    out.write('#endif\n')
    out.close()

if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == '--packed':
        packed(sys.argv)
    else:
        main(sys.argv)
